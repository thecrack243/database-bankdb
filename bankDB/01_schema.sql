-- PostgreSQL schema for a single-bank, multi-branch banking system.
-- Run against a new, empty database. Money is stored as NUMERIC, never FLOAT.

BEGIN;

CREATE TABLE bank (
    bank_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bank_code     TEXT NOT NULL UNIQUE,
    name          TEXT NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT bank_code_not_blank CHECK (btrim(bank_code) <> ''),
    CONSTRAINT bank_name_not_blank CHECK (btrim(name) <> '')
);

CREATE TABLE branch (
    branch_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bank_id       BIGINT NOT NULL REFERENCES bank (bank_id) ON DELETE RESTRICT,
    branch_code   TEXT NOT NULL,
    name          TEXT NOT NULL,
    address       TEXT NOT NULL,
    city          TEXT NOT NULL,
    region        TEXT,
    country_code  TEXT NOT NULL,
    phone         TEXT,
    opened_on     DATE NOT NULL DEFAULT CURRENT_DATE,
    is_active     BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT branch_code_per_bank UNIQUE (bank_id, branch_code),
    CONSTRAINT branch_id_bank_unique UNIQUE (branch_id, bank_id),
    CONSTRAINT branch_country_code_valid CHECK (country_code ~ '^[A-Z]{2}$'),
    CONSTRAINT branch_required_text CHECK (
        btrim(branch_code) <> '' AND btrim(name) <> ''
        AND btrim(address) <> '' AND btrim(city) <> ''
    )
);

CREATE TABLE employee (
    employee_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bank_id           BIGINT NOT NULL REFERENCES bank (bank_id) ON DELETE RESTRICT,
    branch_id         BIGINT NOT NULL,
    employee_number   TEXT NOT NULL,
    manager_id        BIGINT,
    first_name        TEXT NOT NULL,
    last_name         TEXT NOT NULL,
    email             TEXT NOT NULL,
    phone             TEXT,
    job_title         TEXT NOT NULL,
    hired_on          DATE NOT NULL,
    is_active         BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT employee_number_per_bank UNIQUE (bank_id, employee_number),
    CONSTRAINT employee_id_bank_unique UNIQUE (employee_id, bank_id),
    CONSTRAINT employee_branch_same_bank
        FOREIGN KEY (branch_id, bank_id)
        REFERENCES branch (branch_id, bank_id) ON DELETE RESTRICT,
    CONSTRAINT employee_manager_same_bank
        FOREIGN KEY (manager_id, bank_id)
        REFERENCES employee (employee_id, bank_id) ON DELETE RESTRICT,
    CONSTRAINT employee_not_own_manager CHECK (manager_id IS NULL OR manager_id <> employee_id),
    CONSTRAINT employee_required_text CHECK (
        btrim(employee_number) <> '' AND btrim(first_name) <> ''
        AND btrim(last_name) <> '' AND btrim(email) <> ''
        AND btrim(job_title) <> ''
    )
);

CREATE UNIQUE INDEX employee_email_per_bank_uq
    ON employee (bank_id, lower(email));

CREATE TABLE customer (
    customer_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bank_id           BIGINT NOT NULL REFERENCES bank (bank_id) ON DELETE RESTRICT,
    customer_number   TEXT NOT NULL,
    customer_type     TEXT NOT NULL,
    first_name        TEXT,
    last_name         TEXT,
    business_name     TEXT,
    national_id       TEXT,
    tax_id            TEXT,
    email             TEXT,
    phone             TEXT,
    address           TEXT NOT NULL,
    city              TEXT NOT NULL,
    country_code      TEXT NOT NULL,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    is_active         BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT customer_number_per_bank UNIQUE (bank_id, customer_number),
    CONSTRAINT customer_id_bank_unique UNIQUE (customer_id, bank_id),
    CONSTRAINT customer_type_valid CHECK (customer_type IN ('PERSONAL', 'BUSINESS')),
    CONSTRAINT customer_country_code_valid CHECK (country_code ~ '^[A-Z]{2}$'),
    CONSTRAINT customer_type_fields_valid CHECK (
        (customer_type = 'PERSONAL'
            AND btrim(COALESCE(first_name, '')) <> ''
            AND btrim(COALESCE(last_name, '')) <> ''
            AND btrim(COALESCE(national_id, '')) <> ''
            AND business_name IS NULL AND tax_id IS NULL)
        OR
        (customer_type = 'BUSINESS'
            AND btrim(COALESCE(business_name, '')) <> ''
            AND btrim(COALESCE(tax_id, '')) <> ''
            AND first_name IS NULL AND last_name IS NULL AND national_id IS NULL)
    ),
    CONSTRAINT customer_address_valid CHECK (
        btrim(address) <> '' AND btrim(city) <> ''
    )
);

CREATE UNIQUE INDEX customer_national_id_per_bank_uq
    ON customer (bank_id, national_id) WHERE national_id IS NOT NULL;
CREATE UNIQUE INDEX customer_tax_id_per_bank_uq
    ON customer (bank_id, tax_id) WHERE tax_id IS NOT NULL;
CREATE UNIQUE INDEX customer_email_per_bank_uq
    ON customer (bank_id, lower(email)) WHERE email IS NOT NULL;

CREATE TABLE ledger_account (
    ledger_account_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bank_id            BIGINT NOT NULL REFERENCES bank (bank_id) ON DELETE RESTRICT,
    branch_id          BIGINT,
    account_code       TEXT NOT NULL,
    name               TEXT NOT NULL,
    ledger_class       TEXT NOT NULL,
    currency           TEXT NOT NULL,
    is_system          BOOLEAN NOT NULL DEFAULT FALSE,
    is_active          BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ledger_code_per_bank UNIQUE (bank_id, account_code),
    CONSTRAINT ledger_account_bank_unique UNIQUE (ledger_account_id, bank_id),
    CONSTRAINT ledger_account_currency_unique
        UNIQUE (ledger_account_id, bank_id, currency),
    CONSTRAINT ledger_account_class_currency_unique
        UNIQUE (ledger_account_id, bank_id, currency, ledger_class),
    CONSTRAINT ledger_branch_same_bank
        FOREIGN KEY (branch_id, bank_id)
        REFERENCES branch (branch_id, bank_id) ON DELETE RESTRICT,
    CONSTRAINT ledger_class_valid CHECK (
        ledger_class IN (
            'CUSTOMER_DEPOSIT', 'CASH_CLEARING', 'LOAN_RECEIVABLE',
            'INTEREST_EXPENSE', 'FEE_INCOME', 'OPENING_EQUITY',
            'ADJUSTMENT_CLEARING'
        )
    ),
    CONSTRAINT ledger_system_class_valid CHECK (
        (ledger_class IN ('CUSTOMER_DEPOSIT', 'LOAN_RECEIVABLE') AND NOT is_system)
        OR
        (ledger_class IN (
            'CASH_CLEARING', 'INTEREST_EXPENSE', 'FEE_INCOME',
            'OPENING_EQUITY', 'ADJUSTMENT_CLEARING'
        ) AND is_system)
    ),
    CONSTRAINT ledger_currency_valid CHECK (currency ~ '^[A-Z]{3}$'),
    CONSTRAINT ledger_required_text CHECK (
        btrim(account_code) <> '' AND btrim(name) <> ''
    ),
    CONSTRAINT system_ledger_without_branch CHECK (
        NOT is_system OR branch_id IS NULL
    )
);

CREATE UNIQUE INDEX one_system_ledger_class_per_currency_uq
    ON ledger_account (bank_id, ledger_class, currency)
    WHERE is_system;

CREATE TABLE bank_account (
    account_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bank_id             BIGINT NOT NULL REFERENCES bank (bank_id) ON DELETE RESTRICT,
    branch_id           BIGINT NOT NULL,
    ledger_account_id   BIGINT NOT NULL,
    account_number      TEXT NOT NULL UNIQUE,
    account_type        TEXT NOT NULL,
    currency            TEXT NOT NULL,
    status              TEXT NOT NULL DEFAULT 'OPEN',
    overdraft_limit     NUMERIC(19, 2) NOT NULL DEFAULT 0,
    interest_rate       NUMERIC(8, 6) NOT NULL DEFAULT 0,
    withdrawal_limit    INTEGER,
    term_months        INTEGER,
    early_withdrawal_penalty_rate NUMERIC(8, 6),
    opened_at           TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    closed_at           TIMESTAMPTZ,
    CONSTRAINT account_id_bank_unique UNIQUE (account_id, bank_id),
    CONSTRAINT account_ledger_unique UNIQUE (ledger_account_id),
    CONSTRAINT account_number_not_blank CHECK (btrim(account_number) <> ''),
    CONSTRAINT account_type_valid CHECK (
        account_type IN ('SAVINGS', 'CHECKING', 'FIXED_DEPOSIT')
    ),
    CONSTRAINT account_status_valid CHECK (status IN ('OPEN', 'FROZEN', 'CLOSED')),
    CONSTRAINT account_currency_valid CHECK (currency ~ '^[A-Z]{3}$'),
    CONSTRAINT account_limits_valid CHECK (
        overdraft_limit >= 0
        AND interest_rate >= 0 AND interest_rate <= 1
        AND (withdrawal_limit IS NULL OR withdrawal_limit >= 0)
        AND (term_months IS NULL OR term_months > 0)
        AND (
            early_withdrawal_penalty_rate IS NULL
            OR (early_withdrawal_penalty_rate >= 0 AND early_withdrawal_penalty_rate <= 1)
        )
    ),
    CONSTRAINT account_product_rules CHECK (
        (account_type = 'SAVINGS'
            AND overdraft_limit = 0 AND withdrawal_limit IS NOT NULL
            AND term_months IS NULL AND early_withdrawal_penalty_rate IS NULL)
        OR
        (account_type = 'CHECKING'
            AND withdrawal_limit IS NULL AND interest_rate = 0
            AND term_months IS NULL AND early_withdrawal_penalty_rate IS NULL)
        OR
        (account_type = 'FIXED_DEPOSIT'
            AND overdraft_limit = 0 AND withdrawal_limit IS NULL
            AND term_months IS NOT NULL
            AND early_withdrawal_penalty_rate IS NOT NULL)
    ),
    CONSTRAINT account_close_date_valid CHECK (
        (status = 'CLOSED' AND closed_at IS NOT NULL)
        OR (status <> 'CLOSED' AND closed_at IS NULL)
    ),
    CONSTRAINT account_branch_same_bank
        FOREIGN KEY (branch_id, bank_id)
        REFERENCES branch (branch_id, bank_id) ON DELETE RESTRICT,
    CONSTRAINT account_ledger_same_bank_currency
        FOREIGN KEY (ledger_account_id, bank_id, currency)
        REFERENCES ledger_account (ledger_account_id, bank_id, currency)
        ON DELETE RESTRICT
);

CREATE FUNCTION enforce_customer_deposit_ledger()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_ledger_class TEXT;
BEGIN
    SELECT ledger_class INTO v_ledger_class
    FROM ledger_account
    WHERE ledger_account_id = NEW.ledger_account_id
      AND bank_id = NEW.bank_id
      AND currency = NEW.currency;
    IF v_ledger_class <> 'CUSTOMER_DEPOSIT' THEN
        RAISE EXCEPTION 'Bank account % must use a CUSTOMER_DEPOSIT ledger account',
            NEW.account_number;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER bank_account_ledger_class
BEFORE INSERT OR UPDATE OF ledger_account_id, bank_id, currency ON bank_account
FOR EACH ROW EXECUTE FUNCTION enforce_customer_deposit_ledger();

CREATE INDEX bank_account_branch_type_idx
    ON bank_account (branch_id, account_type);
