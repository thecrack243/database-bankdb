AFTER INSERT OR UPDATE OR DELETE ON transaction_entry
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION validate_posted_transaction();

CREATE FUNCTION post_deposit(
    p_account_id BIGINT,
    p_amount NUMERIC(19, 2),
    p_reference TEXT,
    p_employee_id BIGINT DEFAULT NULL,
    p_description TEXT DEFAULT NULL
)
RETURNS BIGINT
LANGUAGE plpgsql
AS $$
DECLARE
    v_account bank_account%ROWTYPE;
    v_cash_ledger_id BIGINT;
    v_transaction_id BIGINT;
BEGIN
    IF p_amount <= 0 THEN
        RAISE EXCEPTION 'Deposit amount must be greater than zero';
    END IF;
    SELECT * INTO v_account
    FROM bank_account
    WHERE account_id = p_account_id
    FOR UPDATE;
    IF NOT FOUND OR v_account.status <> 'OPEN' THEN
        RAISE EXCEPTION 'Account % does not exist or is not open', p_account_id;
    END IF;
    IF v_account.account_type = 'FIXED_DEPOSIT'
       AND EXISTS (
           SELECT 1 FROM transaction_entry
           WHERE ledger_account_id = v_account.ledger_account_id
       ) THEN
        RAISE EXCEPTION 'Deposits into a fixed deposit are only allowed at initial funding';
    END IF;

    SELECT ledger_account_id INTO v_cash_ledger_id
    FROM ledger_account
    WHERE bank_id = v_account.bank_id
      AND ledger_class = 'CASH_CLEARING'
      AND currency = v_account.currency
      AND is_system AND is_active;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'No active cash-clearing ledger account for bank %, currency %',
            v_account.bank_id, v_account.currency;
    END IF;

    INSERT INTO bank_transaction (
        bank_id, reference, transaction_type, currency,
        branch_id, employee_id, description
    ) VALUES (
        v_account.bank_id, p_reference, 'DEPOSIT', v_account.currency,
        v_account.branch_id, p_employee_id, p_description
    ) RETURNING transaction_id INTO v_transaction_id;

    INSERT INTO transaction_entry (bank_id, transaction_id, ledger_account_id, amount)
    VALUES
        (v_account.bank_id, v_transaction_id, v_account.ledger_account_id, p_amount),
        (v_account.bank_id, v_transaction_id, v_cash_ledger_id, -p_amount);

    UPDATE bank_transaction
    SET status = 'POSTED', posted_at = clock_timestamp()
    WHERE transaction_id = v_transaction_id;
    RETURN v_transaction_id;
END;
$$;

CREATE FUNCTION post_withdrawal(
    p_account_id BIGINT,
    p_amount NUMERIC(19, 2),
    p_reference TEXT,
    p_employee_id BIGINT DEFAULT NULL,
    p_description TEXT DEFAULT NULL
)
RETURNS BIGINT
LANGUAGE plpgsql
AS $$
DECLARE
    v_account bank_account%ROWTYPE;
    v_balance NUMERIC(19, 2);
    v_penalty NUMERIC(19, 2);
    v_total_debit NUMERIC(19, 2);
    v_cash_ledger_id BIGINT;
    v_fee_ledger_id BIGINT;
    v_transaction_id BIGINT;
    v_transaction_type TEXT;
BEGIN
    IF p_amount <= 0 THEN
        RAISE EXCEPTION 'Withdrawal amount must be greater than zero';
    END IF;
    SELECT * INTO v_account
    FROM bank_account
    WHERE account_id = p_account_id
    FOR UPDATE;
    IF NOT FOUND OR v_account.status <> 'OPEN' THEN
        RAISE EXCEPTION 'Account % does not exist or is not open', p_account_id;
    END IF;

    v_penalty := account_debit_penalty(p_account_id, p_amount, 'WITHDRAWAL');
    v_total_debit := p_amount + v_penalty;
    SELECT current_balance INTO v_balance
    FROM account_balances
    WHERE account_id = p_account_id;
    IF v_total_debit > v_balance + v_account.overdraft_limit THEN
        RAISE EXCEPTION 'Insufficient funds for account %', p_account_id;
    END IF;

    SELECT ledger_account_id INTO v_cash_ledger_id
    FROM ledger_account
    WHERE bank_id = v_account.bank_id
      AND ledger_class = 'CASH_CLEARING'
      AND currency = v_account.currency
      AND is_system AND is_active;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'No active cash-clearing ledger account for bank %, currency %',
            v_account.bank_id, v_account.currency;
    END IF;
    IF v_penalty > 0 THEN
        SELECT ledger_account_id INTO v_fee_ledger_id
        FROM ledger_account
        WHERE bank_id = v_account.bank_id
          AND ledger_class = 'FEE_INCOME'
          AND currency = v_account.currency
          AND is_system AND is_active;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'No active fee-income ledger account for bank %, currency %',
                v_account.bank_id, v_account.currency;
        END IF;
    END IF;

    v_transaction_type := CASE
        WHEN v_penalty > 0 THEN 'EARLY_WITHDRAWAL'
        ELSE 'WITHDRAWAL'
    END;

    INSERT INTO bank_transaction (
        bank_id, reference, transaction_type, currency,
        branch_id, employee_id, description
    ) VALUES (
        v_account.bank_id, p_reference, v_transaction_type, v_account.currency,
        v_account.branch_id, p_employee_id, p_description
    ) RETURNING transaction_id INTO v_transaction_id;

    INSERT INTO transaction_entry (bank_id, transaction_id, ledger_account_id, amount)
    VALUES
        (v_account.bank_id, v_transaction_id, v_account.ledger_account_id, -v_total_debit),
        (v_account.bank_id, v_transaction_id, v_cash_ledger_id, p_amount);
    IF v_penalty > 0 THEN
        INSERT INTO transaction_entry (bank_id, transaction_id, ledger_account_id, amount)
        VALUES (v_account.bank_id, v_transaction_id, v_fee_ledger_id, v_penalty);
    END IF;

    UPDATE bank_transaction
    SET status = 'POSTED', posted_at = clock_timestamp()
    WHERE transaction_id = v_transaction_id;
    RETURN v_transaction_id;
END;
$$;

CREATE FUNCTION post_transfer(
    p_from_account_id BIGINT,
    p_to_account_id BIGINT,
    p_amount NUMERIC(19, 2),
    p_reference TEXT,
    p_employee_id BIGINT DEFAULT NULL,
    p_description TEXT DEFAULT NULL
)
RETURNS BIGINT
LANGUAGE plpgsql
AS $$
DECLARE
    v_from bank_account%ROWTYPE;
    v_to bank_account%ROWTYPE;
    v_balance NUMERIC(19, 2);
    v_transaction_id BIGINT;
BEGIN
    IF p_amount <= 0 THEN
        RAISE EXCEPTION 'Transfer amount must be greater than zero';
    END IF;
    IF p_from_account_id = p_to_account_id THEN
        RAISE EXCEPTION 'Source and destination accounts must differ';
    END IF;

    PERFORM account_id
    FROM bank_account
    WHERE account_id IN (p_from_account_id, p_to_account_id)
    ORDER BY account_id
    FOR UPDATE;

    SELECT * INTO v_from FROM bank_account WHERE account_id = p_from_account_id;
    SELECT * INTO v_to FROM bank_account WHERE account_id = p_to_account_id;
    IF v_from.account_id IS NULL OR v_to.account_id IS NULL
       OR v_from.status <> 'OPEN' OR v_to.status <> 'OPEN' THEN
        RAISE EXCEPTION 'Both transfer accounts must exist and be open';
    END IF;
    IF v_from.bank_id <> v_to.bank_id OR v_from.currency <> v_to.currency THEN
        RAISE EXCEPTION 'Transfer accounts must belong to the same bank and use the same currency';
    END IF;
    IF v_to.account_type = 'FIXED_DEPOSIT' THEN
        RAISE EXCEPTION 'Transfers into fixed-deposit accounts are not allowed';
    END IF;

    PERFORM account_debit_penalty(p_from_account_id, p_amount, 'TRANSFER');
    SELECT current_balance INTO v_balance
    FROM account_balances
    WHERE account_id = p_from_account_id;
    IF p_amount > v_balance + v_from.overdraft_limit THEN
        RAISE EXCEPTION 'Insufficient funds for account %', p_from_account_id;
    END IF;

    INSERT INTO bank_transaction (
        bank_id, reference, transaction_type, currency,
        branch_id, employee_id, description
    ) VALUES (
        v_from.bank_id, p_reference, 'TRANSFER', v_from.currency,
        v_from.branch_id, p_employee_id, p_description
    ) RETURNING transaction_id INTO v_transaction_id;

    INSERT INTO transaction_entry (bank_id, transaction_id, ledger_account_id, amount)
    VALUES
        (v_from.bank_id, v_transaction_id, v_from.ledger_account_id, -p_amount),
        (v_to.bank_id, v_transaction_id, v_to.ledger_account_id, p_amount);

    UPDATE bank_transaction
    SET status = 'POSTED', posted_at = clock_timestamp()
    WHERE transaction_id = v_transaction_id;
    RETURN v_transaction_id;
END;
$$;

CREATE FUNCTION post_loan_disbursement(
    p_loan_id BIGINT,
    p_reference TEXT,
    p_employee_id BIGINT DEFAULT NULL,
    p_description TEXT DEFAULT NULL
)
RETURNS BIGINT
LANGUAGE plpgsql
AS $$
DECLARE
    v_loan loan%ROWTYPE;
    v_account bank_account%ROWTYPE;
    v_transaction_id BIGINT;
BEGIN
    SELECT * INTO v_loan
    FROM loan
    WHERE loan_id = p_loan_id
    FOR UPDATE;
    IF NOT FOUND OR v_loan.status <> 'APPROVED' THEN
        RAISE EXCEPTION 'Loan % must exist and be APPROVED before disbursement', p_loan_id;
    END IF;

    SELECT * INTO v_account
    FROM bank_account
    WHERE account_id = v_loan.disbursement_account_id
    FOR UPDATE;
    IF NOT FOUND OR v_account.status <> 'OPEN' THEN
        RAISE EXCEPTION 'Loan disbursement account must be open';
    END IF;
    IF v_account.bank_id <> v_loan.bank_id
       OR v_account.currency <> v_loan.currency THEN
        RAISE EXCEPTION 'Loan and disbursement account bank/currency do not match';
    END IF;
    IF v_account.account_type = 'FIXED_DEPOSIT' THEN
        RAISE EXCEPTION 'Loans cannot be disbursed into fixed-deposit accounts';
    END IF;
    IF NOT EXISTS (
        SELECT 1
        FROM account_holder
        WHERE account_id = v_account.account_id
          AND customer_id = v_loan.customer_id
          AND bank_id = v_loan.bank_id
          AND removed_at IS NULL
    ) THEN
        RAISE EXCEPTION 'Borrower must be an active holder of the disbursement account';
    END IF;

    INSERT INTO bank_transaction (
        bank_id, reference, transaction_type, currency,
        branch_id, employee_id, loan_id, description
    ) VALUES (
        v_loan.bank_id, p_reference, 'LOAN_DISBURSEMENT', v_loan.currency,
        v_loan.branch_id, p_employee_id, v_loan.loan_id, p_description
    ) RETURNING transaction_id INTO v_transaction_id;

    INSERT INTO transaction_entry (bank_id, transaction_id, ledger_account_id, amount)
    VALUES
        (v_loan.bank_id, v_transaction_id, v_account.ledger_account_id, v_loan.principal),
        (v_loan.bank_id, v_transaction_id, v_loan.ledger_account_id, -v_loan.principal);

    UPDATE bank_transaction
    SET status = 'POSTED', posted_at = clock_timestamp()
    WHERE transaction_id = v_transaction_id;

    UPDATE loan
    SET status = 'ACTIVE', disbursed_at = clock_timestamp()
    WHERE loan_id = v_loan.loan_id;
    RETURN v_transaction_id;
END;
$$;

CREATE FUNCTION post_loan_repayment(
    p_loan_id BIGINT,
    p_account_id BIGINT,
    p_amount NUMERIC(19, 2),
    p_reference TEXT,
    p_employee_id BIGINT DEFAULT NULL,
    p_description TEXT DEFAULT NULL
)
RETURNS BIGINT
LANGUAGE plpgsql
AS $$
DECLARE
    v_loan loan%ROWTYPE;
    v_account bank_account%ROWTYPE;
    v_balance NUMERIC(19, 2);
    v_outstanding NUMERIC(19, 2);
    v_transaction_id BIGINT;
BEGIN
    IF p_amount <= 0 THEN
        RAISE EXCEPTION 'Repayment amount must be greater than zero';
    END IF;
    SELECT * INTO v_loan
    FROM loan
    WHERE loan_id = p_loan_id
    FOR UPDATE;
    IF NOT FOUND OR v_loan.status <> 'ACTIVE' THEN
        RAISE EXCEPTION 'Loan % must be ACTIVE to accept a repayment', p_loan_id;
    END IF;

    SELECT * INTO v_account
    FROM bank_account
    WHERE account_id = p_account_id
    FOR UPDATE;
    IF NOT FOUND OR v_account.status <> 'OPEN' THEN
        RAISE EXCEPTION 'Repayment account must exist and be open';
    END IF;
    IF v_account.bank_id <> v_loan.bank_id
       OR v_account.currency <> v_loan.currency THEN
        RAISE EXCEPTION 'Loan and repayment account bank/currency do not match';
    END IF;
    IF NOT EXISTS (
        SELECT 1
        FROM account_holder
        WHERE account_id = v_account.account_id
          AND customer_id = v_loan.customer_id
          AND bank_id = v_loan.bank_id
          AND removed_at IS NULL
    ) THEN
        RAISE EXCEPTION 'Borrower must be an active holder of the repayment account';
    END IF;

    PERFORM account_debit_penalty(p_account_id, p_amount, 'LOAN_REPAYMENT');
    SELECT current_balance INTO v_balance
    FROM account_balances
    WHERE account_id = p_account_id;
    IF p_amount > v_balance + v_account.overdraft_limit THEN
        RAISE EXCEPTION 'Insufficient funds for repayment account %', p_account_id;
    END IF;

    SELECT outstanding_balance INTO v_outstanding
    FROM loan_balances
    WHERE loan_id = p_loan_id;
    IF p_amount > v_outstanding THEN
        RAISE EXCEPTION 'Repayment exceeds loan outstanding balance of %', v_outstanding;
    END IF;

    INSERT INTO bank_transaction (
        bank_id, reference, transaction_type, currency,
        branch_id, employee_id, loan_id, description
    ) VALUES (
        v_loan.bank_id, p_reference, 'LOAN_REPAYMENT', v_loan.currency,
        v_loan.branch_id, p_employee_id, v_loan.loan_id, p_description
    ) RETURNING transaction_id INTO v_transaction_id;

    INSERT INTO transaction_entry (bank_id, transaction_id, ledger_account_id, amount)
    VALUES
        (v_loan.bank_id, v_transaction_id, v_account.ledger_account_id, -p_amount),
        (v_loan.bank_id, v_transaction_id, v_loan.ledger_account_id, p_amount);

    UPDATE bank_transaction
    SET status = 'POSTED', posted_at = clock_timestamp()
    WHERE transaction_id = v_transaction_id;

    INSERT INTO loan_payment (bank_id, loan_id, transaction_id, amount)
    VALUES (v_loan.bank_id, v_loan.loan_id, v_transaction_id, p_amount);

    IF p_amount = v_outstanding THEN
        UPDATE loan SET status = 'PAID_OFF' WHERE loan_id = v_loan.loan_id;
    END IF;
    RETURN v_transaction_id;
END;
$$;

