CREATE FUNCTION require_active_account_owner()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_account_ids BIGINT[];
    v_account_id BIGINT;
    v_status TEXT;
BEGIN
    IF TG_TABLE_NAME = 'bank_account' THEN
        v_account_ids := ARRAY[
            CASE WHEN TG_OP = 'DELETE' THEN OLD.account_id ELSE NEW.account_id END
        ];
    ELSIF TG_OP = 'UPDATE' THEN
        v_account_ids := ARRAY[OLD.account_id, NEW.account_id];
    ELSE
        v_account_ids := ARRAY[
            CASE WHEN TG_OP = 'DELETE' THEN OLD.account_id ELSE NEW.account_id END
        ];
    END IF;

    FOREACH v_account_id IN ARRAY v_account_ids LOOP
        SELECT status INTO v_status
        FROM bank_account
        WHERE account_id = v_account_id;
        IF FOUND AND v_status <> 'CLOSED' AND NOT EXISTS (
            SELECT 1
            FROM account_holder
            WHERE account_id = v_account_id
              AND removed_at IS NULL
              AND holder_role IN ('OWNER', 'JOINT_OWNER')
        ) THEN
            RAISE EXCEPTION 'Open or frozen account % must have an active owner',
                v_account_id;
        END IF;
    END LOOP;
    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER bank_account_requires_owner
AFTER INSERT OR UPDATE OR DELETE ON bank_account
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION require_active_account_owner();

CREATE CONSTRAINT TRIGGER account_holder_requires_owner
AFTER INSERT OR UPDATE OR DELETE ON account_holder
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION require_active_account_owner();

