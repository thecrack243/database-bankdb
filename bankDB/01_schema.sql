CREATE FUNCTION enforce_loan_receivable_ledger()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_ledger_class TEXT;
BEGIN
    SELECT ledger_class INTO v_ledger_class
    FROM ledger_account
    WHERE ledger_account_id = NEW.ledger_account_id
      AND bank_id = NEW.bank_id
      AND currency = NEW.currency;
    IF v_ledger_class <> 'LOAN_RECEIVABLE' THEN
        RAISE EXCEPTION 'Loan % must use a LOAN_RECEIVABLE ledger account',
            NEW.loan_number;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER loan_ledger_class
BEFORE INSERT OR UPDATE OF ledger_account_id, bank_id, currency ON loan
