CREATE VIEW account_balances AS
SELECT
    a.account_id,
    a.account_number,
    a.bank_id,
    a.currency,
    COALESCE(SUM(e.amount) FILTER (WHERE t.status = 'POSTED'), 0)::NUMERIC(19, 2)
        AS current_balance
FROM bank_account AS a
LEFT JOIN transaction_entry AS e
    ON e.ledger_account_id = a.ledger_account_id
LEFT JOIN bank_transaction AS t
    ON t.transaction_id = e.transaction_id
   AND t.status = 'POSTED'
GROUP BY a.account_id, a.account_number, a.bank_id, a.currency;

CREATE VIEW loan_balances AS
SELECT
    l.loan_id,
    l.loan_number,
    l.bank_id,
    l.currency,
    GREATEST(
        0,
        -COALESCE(SUM(e.amount) FILTER (WHERE t.status = 'POSTED'), 0)
    )::NUMERIC(19, 2) AS outstanding_balance
FROM loan AS l
LEFT JOIN transaction_entry AS e
    ON e.ledger_account_id = l.ledger_account_id
LEFT JOIN bank_transaction AS t
    ON t.transaction_id = e.transaction_id
   AND t.status = 'POSTED'
GROUP BY l.loan_id, l.loan_number, l.bank_id, l.currency;

CREATE FUNCTION account_debit_penalty(
    p_account_id BIGINT,
    p_amount NUMERIC(19, 2),
    p_operation TEXT
)
RETURNS NUMERIC(19, 2)
LANGUAGE plpgsql
AS $$
DECLARE
    v_account bank_account%ROWTYPE;
    v_debits_this_month BIGINT;
BEGIN
    SELECT * INTO v_account
    FROM bank_account
    WHERE account_id = p_account_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Account % does not exist', p_account_id;
    END IF;

    IF v_account.account_type = 'SAVINGS' AND v_account.withdrawal_limit IS NOT NULL THEN
        SELECT COUNT(DISTINCT t.transaction_id) INTO v_debits_this_month
        FROM transaction_entry AS e
        JOIN bank_transaction AS t
          ON t.transaction_id = e.transaction_id
         AND t.bank_id = e.bank_id
        WHERE e.ledger_account_id = v_account.ledger_account_id
          AND e.amount < 0
          AND t.status = 'POSTED'
          AND t.transaction_type IN (
              'WITHDRAWAL', 'EARLY_WITHDRAWAL', 'TRANSFER', 'LOAN_REPAYMENT'
          )
          AND date_trunc('month', t.posted_at) =
              date_trunc('month', clock_timestamp());
        IF v_debits_this_month >= v_account.withdrawal_limit THEN
            RAISE EXCEPTION 'Monthly withdrawal limit reached for account %',
                p_account_id;
        END IF;
    END IF;

    IF v_account.account_type = 'FIXED_DEPOSIT'
       AND clock_timestamp() < v_account.opened_at
           + make_interval(months => v_account.term_months) THEN
        IF p_operation <> 'WITHDRAWAL' THEN
            RAISE EXCEPTION 'Fixed deposit cannot be debited before maturity by %',
                p_operation;
        END IF;
        RETURN round(p_amount * v_account.early_withdrawal_penalty_rate, 2);
    END IF;
    RETURN 0;
END;
$$;

CREATE FUNCTION guard_bank_transaction()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.status = 'POSTED' THEN
        RAISE EXCEPTION 'Posted transactions are immutable (transaction_id=%)', OLD.transaction_id;
    END IF;
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER bank_transaction_immutable
BEFORE UPDATE OR DELETE ON bank_transaction
FOR EACH ROW EXECUTE FUNCTION guard_bank_transaction();

CREATE FUNCTION guard_transaction_entry()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_transaction_id BIGINT;
    v_old_status TEXT;
    v_status TEXT;
BEGIN
    IF TG_OP = 'UPDATE' THEN
        SELECT status INTO v_old_status
        FROM bank_transaction
        WHERE transaction_id = OLD.transaction_id;
        IF v_old_status = 'POSTED' THEN
            RAISE EXCEPTION 'Entries belonging to a posted transaction are immutable';
        END IF;
    END IF;

    v_transaction_id := CASE WHEN TG_OP = 'DELETE'
        THEN OLD.transaction_id ELSE NEW.transaction_id END;

    SELECT status INTO v_status
    FROM bank_transaction
    WHERE transaction_id = v_transaction_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Transaction % does not exist', v_transaction_id;
    END IF;
    IF v_status <> 'PENDING' THEN
        RAISE EXCEPTION 'Entries may only be changed while a transaction is PENDING';
    END IF;
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER transaction_entry_guard
BEFORE INSERT OR UPDATE OR DELETE ON transaction_entry
FOR EACH ROW EXECUTE FUNCTION guard_transaction_entry();

CREATE FUNCTION validate_posted_transaction()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_transaction_id BIGINT;
    v_type TEXT;
    v_status TEXT;
    v_loan_id BIGINT;
    v_entry_count BIGINT;
    v_positive_count BIGINT;
    v_negative_count BIGINT;
    v_total NUMERIC(19, 2);
    v_customer_positive BIGINT;
    v_customer_negative BIGINT;
    v_cash_positive BIGINT;
    v_cash_negative BIGINT;
    v_interest_negative BIGINT;
    v_fee_positive BIGINT;
    v_loan_positive BIGINT;
    v_loan_negative BIGINT;
    v_distinct_ledgers BIGINT;
    v_wrong_currency BIGINT;
    v_wrong_loan_ledger BIGINT;
BEGIN
    IF TG_TABLE_NAME = 'bank_transaction' THEN
        v_transaction_id := CASE WHEN TG_OP = 'DELETE'
            THEN OLD.transaction_id ELSE NEW.transaction_id END;
    ELSE
        v_transaction_id := CASE WHEN TG_OP = 'DELETE'
            THEN OLD.transaction_id ELSE NEW.transaction_id END;
    END IF;

    SELECT transaction_type, status, loan_id
    INTO v_type, v_status, v_loan_id
    FROM bank_transaction
    WHERE transaction_id = v_transaction_id;

    IF NOT FOUND OR v_status <> 'POSTED' THEN
        RETURN NULL;
    END IF;

    SELECT
        COUNT(*),
        COUNT(*) FILTER (WHERE e.amount > 0),
        COUNT(*) FILTER (WHERE e.amount < 0),
        COALESCE(SUM(e.amount), 0),
        COUNT(*) FILTER (WHERE a.ledger_class = 'CUSTOMER_DEPOSIT' AND e.amount > 0),
        COUNT(*) FILTER (WHERE a.ledger_class = 'CUSTOMER_DEPOSIT' AND e.amount < 0),
        COUNT(*) FILTER (WHERE a.ledger_class = 'CASH_CLEARING' AND e.amount > 0),
        COUNT(*) FILTER (WHERE a.ledger_class = 'CASH_CLEARING' AND e.amount < 0),
        COUNT(*) FILTER (WHERE a.ledger_class = 'INTEREST_EXPENSE' AND e.amount < 0),
        COUNT(*) FILTER (WHERE a.ledger_class = 'FEE_INCOME' AND e.amount > 0),
        COUNT(*) FILTER (WHERE a.ledger_class = 'LOAN_RECEIVABLE' AND e.amount > 0),
        COUNT(*) FILTER (WHERE a.ledger_class = 'LOAN_RECEIVABLE' AND e.amount < 0),
        COUNT(DISTINCT e.ledger_account_id),
        COUNT(*) FILTER (WHERE a.currency <> t.currency),
        COUNT(*) FILTER (
            WHERE l.loan_id IS NOT NULL
              AND e.ledger_account_id = l.ledger_account_id
        )
    INTO
        v_entry_count, v_positive_count, v_negative_count, v_total,
        v_customer_positive, v_customer_negative, v_cash_positive, v_cash_negative,
        v_interest_negative, v_fee_positive, v_loan_positive, v_loan_negative,
        v_distinct_ledgers, v_wrong_currency, v_wrong_loan_ledger
    FROM transaction_entry AS e
    JOIN ledger_account AS a
      ON a.ledger_account_id = e.ledger_account_id
     AND a.bank_id = e.bank_id
    JOIN bank_transaction AS t
      ON t.transaction_id = e.transaction_id
     AND t.bank_id = e.bank_id
    LEFT JOIN loan AS l
      ON l.loan_id = t.loan_id
     AND l.bank_id = t.bank_id
    WHERE e.transaction_id = v_transaction_id;

    IF v_entry_count < 2 OR v_positive_count = 0 OR v_negative_count = 0 OR v_total <> 0 THEN
        RAISE EXCEPTION 'Posted transaction % must have balanced, non-zero ledger entries',
            v_transaction_id;
    END IF;
    IF v_wrong_currency <> 0 THEN
        RAISE EXCEPTION 'Ledger-entry currency does not match transaction %', v_transaction_id;
    END IF;

    IF v_type = 'DEPOSIT' AND NOT (
        v_entry_count = 2 AND v_customer_positive = 1 AND v_cash_negative = 1
    ) THEN
        RAISE EXCEPTION 'Deposit % must credit one customer account and debit cash clearing',
            v_transaction_id;
    ELSIF v_type = 'WITHDRAWAL' AND NOT (
        v_entry_count = 2 AND v_customer_negative = 1 AND v_cash_positive = 1
    ) THEN
        RAISE EXCEPTION 'Withdrawal % has invalid ledger entries', v_transaction_id;
    ELSIF v_type = 'EARLY_WITHDRAWAL' AND NOT (
        v_entry_count = 3 AND v_customer_negative = 1
        AND v_cash_positive = 1 AND v_fee_positive = 1
    ) THEN
        RAISE EXCEPTION 'Early fixed-deposit withdrawal % has invalid ledger entries',
            v_transaction_id;
    ELSIF v_type = 'TRANSFER' AND NOT (
        v_entry_count = 2 AND v_customer_positive = 1
        AND v_customer_negative = 1 AND v_distinct_ledgers = 2
    ) THEN
        RAISE EXCEPTION 'Transfer % must move equal value between two customer accounts',
            v_transaction_id;
    ELSIF v_type = 'INTEREST' AND NOT (
        v_entry_count = 2 AND v_customer_positive = 1 AND v_interest_negative = 1
    ) THEN
        RAISE EXCEPTION 'Interest transaction % has invalid ledger entries', v_transaction_id;
    ELSIF v_type = 'FEE' AND NOT (
        v_entry_count = 2 AND v_customer_negative = 1 AND v_fee_positive = 1
    ) THEN
        RAISE EXCEPTION 'Fee transaction % has invalid ledger entries', v_transaction_id;
    ELSIF v_type = 'LOAN_DISBURSEMENT' AND NOT (
        v_entry_count = 2 AND v_customer_positive = 1 AND v_loan_negative = 1
        AND v_wrong_loan_ledger = 1
    ) THEN
        RAISE EXCEPTION 'Loan disbursement % has invalid ledger entries', v_transaction_id;
    ELSIF v_type = 'LOAN_REPAYMENT' AND NOT (
        v_entry_count = 2 AND v_customer_negative = 1 AND v_loan_positive = 1
        AND v_wrong_loan_ledger = 1
    ) THEN
        RAISE EXCEPTION 'Loan repayment % has invalid ledger entries', v_transaction_id;
    ELSIF v_type = 'ADJUSTMENT' AND v_entry_count < 2 THEN
        RAISE EXCEPTION 'Adjustment % must have at least two ledger entries', v_transaction_id;
    END IF;

    RETURN NULL;
END;
$$;

