CREATE FUNCTION validate_loan_payment()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_transaction bank_transaction%ROWTYPE;
    v_customer_debit NUMERIC(19, 2);
    v_loan_credit NUMERIC(19, 2);
BEGIN
    SELECT * INTO v_transaction
    FROM bank_transaction
    WHERE transaction_id = NEW.transaction_id
      AND bank_id = NEW.bank_id;
    IF NOT FOUND
       OR v_transaction.status <> 'POSTED'
       OR v_transaction.transaction_type <> 'LOAN_REPAYMENT'
       OR v_transaction.loan_id <> NEW.loan_id THEN
        RAISE EXCEPTION 'Loan payment must reference its posted loan-repayment transaction';
    END IF;

    SELECT
        COALESCE(SUM(-e.amount) FILTER (
            WHERE a.ledger_class = 'CUSTOMER_DEPOSIT' AND e.amount < 0
        ), 0),
        COALESCE(SUM(e.amount) FILTER (
            WHERE a.ledger_class = 'LOAN_RECEIVABLE' AND e.amount > 0
        ), 0)
    INTO v_customer_debit, v_loan_credit
    FROM transaction_entry AS e
    JOIN ledger_account AS a
      ON a.ledger_account_id = e.ledger_account_id
     AND a.bank_id = e.bank_id
    WHERE e.transaction_id = NEW.transaction_id;

    IF NEW.amount <> v_customer_debit OR NEW.amount <> v_loan_credit THEN
        RAISE EXCEPTION 'Loan payment amount must match its posted ledger entries';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER loan_payment_matches_transaction
BEFORE INSERT ON loan_payment
FOR EACH ROW EXECUTE FUNCTION validate_loan_payment();

